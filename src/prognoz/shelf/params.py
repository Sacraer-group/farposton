# -*- coding: utf-8 -*-
"""Параметры методики «жизнь позиции на полке». Одно место, где заданы пороги.

Пороги — это методика, а не деталь реализации: от них зависят публикуемые числа.
Поэтому они лежат рядом с unit_costs и scope, попадают в реестр фактов
(shelf.params.*) и имеют историю в facts_history.jsonl — подкрутить их молча нельзя.
"""
from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass
from datetime import date


@dataclass(frozen=True)
class Params:
    # Окно расчёта: тот же год, что в замере «ДО»
    since: date = date(2025, 8, 1)
    until: date = date(2026, 7, 31)

    # Минимум дней жизни пары «точка × позиция» для часового профиля. Меньше —
    # профиль шумит, и вечерняя тишина неотличима от нормы.
    min_days: int = 30

    # «Замолчала рано» = последняя продажа раньше, чем за столько часов до закрытия.
    early_gap_h: float = 1.5

    # Гейт уценки: уценка снимает исход «кончилось рано», только если она ВЕЧЕРНЯЯ —
    # первая у40-строка чека не раньше, чем за столько часов до закрытия. Дневные
    # дробные «уценки» — это скидочные программы (−10%), реконструированные витриной
    # как у40, а не вечерняя распродажа: они не доказывают, что вечером товар был
    # на полке (находка 5 панели проверки, 08.08.2026). Без наблюдаемого времени
    # уценки (нет чековой строки со скидкой >35%) — консервативно старое поведение.
    markdown_evening_h: float = 3.0

    # Маржа вечернего хвоста в день дефицита, где уценка всё же была (дневная):
    # недопроданные вечером штуки ушли бы со скидкой −40%, прибыль 0,60 − 0,33 =
    # 0,27 цены, а не полные 0,67 маржи.
    markdown_margin: float = 0.27

    # Порог значимости дефицита, шт. Если за остаток вечера ожидалось меньше —
    # молчание списываем на случайность, а не на пустую полку. Без порога редкие
    # позиции (наборы по 1–2 шт в день) дают фантомный дефицит: пуассон, а не полка.
    signif_units: float = 2.0

    # Окно привязки акта списания к торговому дню, ±дней. Акт нередко оформляют
    # следующим утром (приём обкатан в economics.order_sales_writeoff_gap).
    wo_window_days: int = 1

    def fingerprint(self) -> str:
        raw = repr(sorted(asdict(self).items())).encode("utf-8")
        return hashlib.sha256(raw).hexdigest()[:12]

    @property
    def period_ru(self) -> str:
        return f"{self.since:%d.%m.%Y}–{self.until:%d.%m.%Y}"


